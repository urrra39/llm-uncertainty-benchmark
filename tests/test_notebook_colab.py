"""`notebooks/run_on_colab.ipynb` has to run unedited on a machine I do not have.

What can be checked without a T4 is checked here: the file is valid notebook
JSON, every code cell parses, the stages it drives are real subcommands, the
config it names exists, the key is read through `getpass`, and the reporting cell
actually works against a real results file. What cannot be checked is whether a
CUDA generation pass produces sensible numbers; that is stated as unverified in
the notebook itself rather than asserted here.

The notebook is generated by `scripts/build_colab_notebook.py`. A test asserts
the committed file matches what that script produces, so the two cannot drift.
"""

from __future__ import annotations

import ast
import json
import subprocess
import sys
from pathlib import Path
from typing import Any

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
NOTEBOOK = REPO_ROOT / "notebooks" / "run_on_colab.ipynb"
BUILDER = REPO_ROOT / "scripts" / "build_colab_notebook.py"


@pytest.fixture(scope="module")
def notebook() -> dict[str, Any]:
    loaded = json.loads(NOTEBOOK.read_text(encoding="utf-8"))
    assert isinstance(loaded, dict)
    return loaded


def _source(cell: dict[str, Any]) -> str:
    return "".join(cell["source"])


def _all_source(notebook: dict[str, Any]) -> str:
    return "\n".join(_source(c) for c in notebook["cells"])


def _code_source(notebook: dict[str, Any]) -> str:
    return "\n".join(_source(c) for c in notebook["cells"] if c["cell_type"] == "code")


def test_notebook_is_valid_nbformat(notebook: dict[str, Any]) -> None:
    # A malformed .ipynb fails when the reader opens it, not when a cell runs,
    # so "it is valid JSON in the right shape" is worth pinning.
    assert notebook["nbformat"] == 4
    assert notebook["cells"]
    for cell in notebook["cells"]:
        assert cell["cell_type"] in ("code", "markdown")
        assert isinstance(cell["source"], list)
        assert all(isinstance(line, str) for line in cell["source"])
        if cell["cell_type"] == "code":
            assert cell["outputs"] == []
            assert cell["execution_count"] is None


def test_every_code_cell_parses(notebook: dict[str, Any]) -> None:
    for index, cell in enumerate(notebook["cells"]):
        if cell["cell_type"] != "code":
            continue
        try:
            ast.parse(_source(cell))
        except SyntaxError as exc:  # pragma: no cover - the assertion is the point
            raise AssertionError(f"cell {index} does not parse: {exc}") from exc


def test_notebook_matches_its_generator() -> None:
    # Regenerating must be a no-op. Otherwise the committed notebook is a
    # hand-edit the generator would silently overwrite.
    proc = subprocess.run(
        [sys.executable, str(BUILDER)],
        capture_output=True,
        text=True,
        cwd=REPO_ROOT,
        check=False,
    )
    assert proc.returncode == 0, proc.stderr
    after = NOTEBOOK.read_text(encoding="utf-8")
    proc2 = subprocess.run(
        [sys.executable, str(BUILDER)],
        capture_output=True,
        text=True,
        cwd=REPO_ROOT,
        check=False,
    )
    assert proc2.returncode == 0, proc2.stderr
    assert NOTEBOOK.read_text(encoding="utf-8") == after


