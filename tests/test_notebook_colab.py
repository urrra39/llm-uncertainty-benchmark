def test_notebook_stage_names_are_real_subcommands(notebook: dict[str, Any]) -> None:
    # A typo in a subcommand name would fail 70 minutes in. Check the names
    # against the parser rather than against a hand-copied list.
    from unc_bench.cli import build_parser

    actions = [a for a in build_parser()._actions if a.__class__.__name__ == "_SubParsersAction"]
    assert actions, "the CLI has no subparsers"
    choices = actions[0].choices or {}
    known = set(choices)

    tree = ast.parse(_code_source(notebook))
    called: set[str] = set()
    for node in ast.walk(tree):
        if (
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Name)
            and node.func.id == "stage"
            and node.args
            and isinstance(node.args[0], ast.Constant)
            and isinstance(node.args[0].value, str)
        ):
            called.add(node.args[0].value)
    assert called
    assert called <= known, sorted(called - known)


