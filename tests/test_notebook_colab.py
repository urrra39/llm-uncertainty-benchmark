def test_no_superseded_runtime_estimate_survives(notebook: dict[str, Any]) -> None:
    # The estimate given before D27 was measured was 55-70 min with a 45 min - 2 h
    # band. It is wrong and must not appear anywhere in the notebook.
    text = _all_source(notebook)
